export type MaterialCategory = { code: string; name: string }

export type Material = {
  /** 物料编码，如 0000390905 */
  code: string
  categoryCode: string
  /** 二级分类，如 箱梁模板 */
  subCategory: string
  name: string
  spec: string
  unit: string
  auxUnit?: string
  tags?: string[]
}

