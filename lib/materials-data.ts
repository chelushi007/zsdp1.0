export function categoryName(code: string) {
  return materialCategories.find((c) => c.code === code)?.name ?? code
}

/** 分类编号-物料编码 */
export function materialFullCode(m: Material) {
  return `${m.categoryCode}${m.code}`
}

export function materialCategoryPath(m: Material) {
  return `${categoryName(m.categoryCode)}/${m.subCategory}`
}

